"""Tests for scripts/gen-seo.sh on a fixture docs tree (never the live docs)."""

import shutil
import subprocess
from pathlib import Path

import pytest

BASH = shutil.which("bash")
if BASH is None:
    pytest.skip("gen-seo.sh tests require bash on PATH", allow_module_level=True)

ROOT = Path(__file__).parents[1]
GEN_SEO = ROOT / "scripts" / "gen-seo.sh"
BASE = "https://splunkctl.danny.vn"

SIDEBAR = """- [Home](/)

- **Getting started**
  - [Install](guides/install.md)
  - [Keycloak lab](guides/keycloak-lab.md)

- **Commands**
  - [Search](guides/search.md)
  - [Old alerts](guides/alerts-old.md)

<!-- commands:start -->
- **Reference**
  - [Overview](commands/README.md)
  - [search](commands/search.md)
<!-- commands:end -->

- **Design**
  - [Architecture](design/architecture.md)

- [GitHub ↗](https://github.com/dannyota/splunkctl)
"""

LONG_SUMMARY = ("Install splunkctl with pipx, uv, or pip. " * 5).strip()[:190]

PAGES = {
    "README.md": (
        "<!-- summary: splunkctl is a CLI and MCP server for Splunk. -->\n"
        "# splunkctl\n\nIntro paragraph.\n\nSee [Install](guides/install.md).\n"
    ),
    "guides/install.md": (
        f"<!-- summary: {LONG_SUMMARY} -->\n# Install\n\nBody.\n\n## Requirements\n\n"
        "```bash\n# not a heading\npip install splunkctl\n```\n\n### Python\n\nText.\n"
    ),
    "guides/keycloak-lab.md": (
        "<!-- summary: Contributor lab for SAML testing. -->\n# Keycloak lab\n\nLab.\n"
    ),
    "guides/search.md": (
        "<!-- summary: Run SPL queries from the terminal. -->\n# Search\n\n"
        "Run searches. See [rules](rules.md) and [SOAR](guides/soar.md)\n"
        "and the [reference](#/commands/search) or [anchor](#usage).\n\n"
        "## Usage\n\nText.\n"
    ),
    "guides/rules.md": "<!-- summary: Manage detection rules. -->\n# Rules\n\nBody.\n",
    "guides/soar.md": "<!-- summary: SOAR overview. -->\n# SOAR\n\nBody.\n",
    "guides/alerts-old.md": (
        "<!-- summary: Alerts moved to the alerts guide. -->\n# Alerts\n\n"
        "This page moved to [Alerts](guides/alerts.md).\n"
    ),
    "commands/README.md": (
        "<!-- Generated by `splunkctl docs generate` — do not edit by hand. -->\n"
        "<!-- summary: Index of every splunkctl command group. -->\n\n"
        "# Command reference\n\nTable.\n"
    ),
    "commands/search.md": (
        "<!-- Generated by `splunkctl docs generate` — do not edit by hand. -->\n"
        "<!-- summary: Reference for `splunkctl search`: Run SPL searches. -->\n\n"
        "# splunkctl search\n\n## search run\n\nText.\n"
    ),
    "design/architecture.md": (
        "<!-- summary: How splunkctl is built. -->\n# Architecture\n\nLayers.\n"
    ),
}


def _tree(tmp_path: Path, pages: dict[str, str] | None = None) -> Path:
    scripts = tmp_path / "scripts"
    scripts.mkdir()
    shutil.copy2(GEN_SEO, scripts / GEN_SEO.name)
    docs = tmp_path / "docs"
    (docs / "_sidebar.md").parent.mkdir()
    (docs / "_sidebar.md").write_text(SIDEBAR, encoding="utf-8")
    for rel, body in (pages or PAGES).items():
        f = docs / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(body, encoding="utf-8")
    return docs


def _run(tmp_path: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(  # noqa: S603
        [BASH, str(tmp_path / "scripts" / GEN_SEO.name), *args],
        cwd=tmp_path,
        check=False,
        capture_output=True,
        text=True,
    )


def test_llms_txt_links_raw_markdown_grouped_by_sidebar_section(
    tmp_path: Path,
) -> None:
    docs = _tree(tmp_path)
    result = _run(tmp_path)
    assert result.returncode == 0, result.stdout + result.stderr
    llms = (docs / "llms.txt").read_text()
    assert llms.startswith("# splunkctl\n\n> ")
    assert "262" not in llms
    assert "#/guides" not in llms
    assert f"- [Home]({BASE}/README.md): splunkctl is a CLI and MCP server" in llms
    assert f"- [Search]({BASE}/guides/search.md): Run SPL queries" in llms
    assert f"- [search]({BASE}/commands/search.md): Reference for" in llms
    machine = llms.index("## Machine-readable")
    assert machine < llms.index("## Getting started") < llms.index("## Commands")
    assert llms.index("## Commands") < llms.index("## Reference")
    assert f"({BASE}/llms-full.txt)" in llms
    assert f"({BASE}/commands.json)" in llms
    assert "## Links" in llms
    assert "[GitHub ↗]" not in llms


def test_llms_txt_uses_summary_verbatim_without_truncation(tmp_path: Path) -> None:
    docs = _tree(tmp_path)
    _run(tmp_path)
    llms = (docs / "llms.txt").read_text()
    assert f"- [Install]({BASE}/guides/install.md): {LONG_SUMMARY}\n" in llms


@pytest.mark.parametrize(
    ("body", "reason"),
    [
        ("# Search\n\nNo summary here.\n", "missing"),
        (
            "<!-- summary: One. -->\n# Search\n\n<!-- summary: Two. -->\nText.\n",
            "duplicate",
        ),
        (f"<!-- summary: {'x' * 201} -->\n# Search\n", "oversized"),
        ("<!-- summary:  -->\n# Search\n", "empty"),
        ("# Search\n\nIntro.\n<!-- summary: Too far down. -->\n", "missing"),
    ],
)
def test_rejects_bad_summaries(tmp_path: Path, body: str, reason: str) -> None:
    pages = {**PAGES, "guides/search.md": body}
    docs = _tree(tmp_path, pages)
    result = _run(tmp_path)
    assert result.returncode == 1
    assert "guides/search.md" in result.stderr
    assert reason in result.stderr
    assert not (docs / "llms.txt").exists()


def test_check_mode_reports_summary_errors_with_files(tmp_path: Path) -> None:
    pages = {**PAGES, "guides/install.md": "# Install\n", "guides/soar.md": "# SOAR\n"}
    docs = _tree(tmp_path, pages)
    (docs / "llms.txt").write_text("x")
    result = _run(tmp_path, "--check")
    assert result.returncode == 1
    assert "missing summary: docs/guides/install.md" in result.stderr
    # soar.md is only linked from a page, not the sidebar: not indexed.
    assert "guides/soar.md" not in result.stderr
    assert "stale:" not in result.stderr
    assert (docs / "llms.txt").read_text() == "x"


def test_llms_full_sections_in_sidebar_order_with_shifted_headings(
    tmp_path: Path,
) -> None:
    docs = _tree(tmp_path)
    _run(tmp_path)
    full = (docs / "llms-full.txt").read_text()
    h1s, fence = [], False
    for ln in full.splitlines():
        if ln.startswith("```"):
            fence = not fence
        elif not fence and ln.startswith("# "):
            h1s.append(ln)
    assert h1s == ["# splunkctl documentation"]
    h2s = [ln for ln in full.splitlines() if ln.startswith("## ")]
    assert h2s == ["## splunkctl", "## Install", "## Search"]
    assert "### Requirements" in full
    assert "#### Python" in full
    assert "### Usage" in full
    assert "# not a heading" in full
    assert f"Source: {BASE}/README.md" in full
    assert f"Source: {BASE}/guides/install.md" in full
    source = full.index(f"Source: {BASE}/guides/install.md")
    assert full.index("## Install") < source < full.index("### Requirements")
    assert "<!-- summary:" not in full
    assert full.count(f"Source: {BASE}/guides/install.md") == 1


def test_llms_full_omits_generated_lab_design_stubs_and_navigation(
    tmp_path: Path,
) -> None:
    docs = _tree(tmp_path)
    _run(tmp_path)
    full = (docs / "llms-full.txt").read_text()
    assert "## search run" not in full
    assert "Keycloak lab" not in full
    assert "Layers." not in full
    assert "This page moved" not in full
    assert "commands:start" not in full
    assert f"{BASE}/commands.json" in full
    assert f"{BASE}/commands/README.md" in full


def test_llms_full_absolutizes_relative_links(tmp_path: Path) -> None:
    docs = _tree(tmp_path)
    _run(tmp_path)
    full = (docs / "llms-full.txt").read_text()
    assert f"[Install]({BASE}/guides/install.md)" in full
    assert f"[rules]({BASE}/guides/rules.md)" in full
    assert f"[SOAR]({BASE}/guides/soar.md)" in full
    assert f"[reference]({BASE}/#/commands/search)" in full
    assert "[anchor](#usage)" in full


def test_sitemap_derived_from_sidebar(tmp_path: Path) -> None:
    docs = _tree(tmp_path)
    _run(tmp_path)
    sitemap = (docs / "sitemap.xml").read_text()
    assert f"<loc>{BASE}/#/</loc>" in sitemap
    assert f"<loc>{BASE}/#/guides/search</loc>" in sitemap
    assert f"<loc>{BASE}/#/commands/search</loc>" in sitemap
    assert f"<loc>{BASE}/#/design/architecture</loc>" in sitemap
    assert "github.com" not in sitemap
    assert sitemap.count("<url>") == 8


def test_check_mode_passes_when_fresh_and_fails_when_stale(tmp_path: Path) -> None:
    docs = _tree(tmp_path)
    assert _run(tmp_path).returncode == 0
    fresh = _run(tmp_path, "--check")
    assert fresh.returncode == 0, fresh.stdout + fresh.stderr
    assert "ok" in fresh.stdout
    (docs / "llms.txt").write_text("stale\n")
    stale = _run(tmp_path, "--check")
    assert stale.returncode == 1
    assert "stale: llms.txt" in stale.stderr
    assert (docs / "llms.txt").read_text() == "stale\n"
